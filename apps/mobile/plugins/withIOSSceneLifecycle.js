const fs = require("fs");
const path = require("path");
const { withAppDelegate, withInfoPlist } = require("@expo/config-plugins");

const sceneDelegate = fs.readFileSync(path.join(__dirname, "ios/SceneDelegate.swift"), "utf8");
const marker = "// @generated by withIOSSceneLifecycle";
const sceneManifest = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [{
      UISceneConfigurationName: "Default Configuration",
      UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate"
    }]
  }
};

function migrateAppDelegate(contents) {
  if (contents.includes(marker)) {
    return contents.slice(0, contents.indexOf(marker)).trimEnd() + `\n\n${marker}\n${sceneDelegate}`;
  }

  // Only migrate the known Expo SDK 54 startup; reject custom code rather than
  // silently leaving a second window/runtime initialization in AppDelegate.
  const startup = /#if os\(iOS\) \|\| os\(tvOS\)\s+window = UIWindow\(frame: UIScreen\.main\.bounds\)\s+factory\.startReactNative\(\s+withModuleName: "main",\s+in: window,\s+launchOptions: launchOptions\)\s+#endif/;
  const factoryProperty = "var reactNativeFactory: RCTReactNativeFactory?";
  const factoryBinding = "bindReactNativeFactory(factory)";
  if (!startup.test(contents) || !contents.includes(factoryProperty) ||
      !contents.includes(factoryBinding) || /class SceneDelegate\b/.test(contents)) {
    throw new Error("withIOSSceneLifecycle requires the Expo SDK 54 Swift AppDelegate template. Review native startup before regenerating iOS.");
  }
  return contents
    .replace(factoryProperty, `${factoryProperty}\n  var appLaunchOptions: [UIApplication.LaunchOptionsKey: Any]?`)
    .replace(factoryBinding, `${factoryBinding}\n    appLaunchOptions = launchOptions`)
    .replace(startup, "    // SceneDelegate creates the window and starts React Native after UIKit connects a scene.")
    .trimEnd() + `\n\n${marker}\n${sceneDelegate}`;
}

module.exports = function withIOSSceneLifecycle(config) {
  config = withInfoPlist(config, (config) => {
    config.modResults.UIApplicationSceneManifest = sceneManifest;
    return config;
  });
  return withAppDelegate(config, (config) => {
    if (config.modResults.language !== "swift") {
      throw new Error("withIOSSceneLifecycle requires a Swift AppDelegate.");
    }
    config.modResults.contents = migrateAppDelegate(config.modResults.contents);
    return config;
  });
};
module.exports.migrateAppDelegate = migrateAppDelegate;
module.exports.sceneManifest = sceneManifest;
