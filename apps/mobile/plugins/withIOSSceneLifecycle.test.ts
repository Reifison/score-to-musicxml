import { createRequire } from "node:module";
import { describe, expect, it } from "vitest";

const require = createRequire(import.meta.url);
const { migrateAppDelegate, sceneManifest } = require("./withIOSSceneLifecycle.js");

// The startup from the Expo SDK 54 template, with an existing linking override.
const legacyDelegate = `
class AppDelegate: ExpoAppDelegate {
  var window: UIWindow?
  var reactNativeFactory: RCTReactNativeFactory?
  func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
    bindReactNativeFactory(factory)
#if os(iOS) || os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif
    return super.application(application, didFinishLaunchingWithOptions: launchOptions)
  }
  // Existing linking overrides must survive native regeneration.
  func openURL() { RCTLinkingManager.application(app, open: url, options: options) }
}`;

describe("iOS scene lifecycle regeneration", () => {
  it("moves startup into the registered scene while preserving Expo and linking hooks", () => {
    const migrated = migrateAppDelegate(legacyDelegate);
    const appDelegate = migrated.split("// @generated by withIOSSceneLifecycle")[0];
    expect(appDelegate).not.toContain("factory.startReactNative(");
    expect(appDelegate).toContain("bindReactNativeFactory(factory)");
    expect(appDelegate).toContain("appLaunchOptions = launchOptions");
    expect(appDelegate).toContain("RCTLinkingManager.application(app, open: url, options: options)");
    expect(migrated).toContain("class SceneDelegate: UIResponder, UIWindowSceneDelegate");
    expect(sceneManifest.UISceneConfigurations.UIWindowSceneSessionRoleApplication[0].UISceneDelegateClassName)
      .toBe("$(PRODUCT_MODULE_NAME).SceneDelegate");
    expect(sceneManifest.UIApplicationSupportsMultipleScenes).toBe(false);
  });

  it("regenerates without adding duplicate scenes and refreshes the owned scene code", () => {
    const migrated = migrateAppDelegate(legacyDelegate);
    expect(migrateAppDelegate(migrated)).toBe(migrated);
    const outdated = migrated.replace("class SceneDelegate:", "class OutdatedSceneDelegate:");
    expect(migrateAppDelegate(outdated)).toBe(migrated);
  });

  it("refuses unfamiliar startup or an existing scene implementation", () => {
    expect(() => migrateAppDelegate(legacyDelegate.replace('withModuleName: "main"', 'withModuleName: "custom"'))).toThrow(/template/);
    expect(() => migrateAppDelegate(legacyDelegate + "\nclass SceneDelegate: UIResponder {}"))
      .toThrow(/template/);
  });
});
