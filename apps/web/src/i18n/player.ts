export function localizePlayerError(
  message: string,
  language: PlayerLanguage,
  fallback: PlayerCopyKey = "genericLoadError"
): string {
  if (message === "Invalid SVG output") return playerCopy(language, "invalidSvgOutput");
  if (message === "Empty MIDI output") return playerCopy(language, "emptyMidiOutput");
  const exact = PLAYER_ERROR_TRANSLATIONS.find(([portuguese]) => portuguese === message);
  if (exact) return playerCopy(language, exact[1]);
  if (message.startsWith("Não foi possível carregar o sample (")) {
    return `${playerCopy(language, "invalidSampleResponse")} ${message.match(/\(\d+\)/)?.[0] ?? ""}`.trim();
  }
  if (message.startsWith("Não foi possível abrir")) return playerCopy(language, "openScoreError");
  if (message.startsWith("Não foi possível preparar o áudio")) return playerCopy(language, "prepareAudioError");
  if (message.startsWith("Não foi possível iniciar o áudio")) return playerCopy(language, "genericStartError");
  if (message.startsWith("Não foi possível alterar o andamento")) return playerCopy(language, "changeTempoError");
  if (language === "pt" && looksPortuguese(message)) return message;
  return playerCopy(language, fallback);
}

function looksPortuguese(message: string): boolean {
  return /[ãõçáéíóú]/i.test(message)
    || /\b(?:Não|Nenhuma|Andamento|Posição|Duração|Trilha|Evento|Esta|Este|Há)\b/i.test(message);
}
