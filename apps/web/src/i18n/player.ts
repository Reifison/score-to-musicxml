export function playerCopy(language: PlayerLanguage, key: PlayerCopyKey): string {
  return PLAYER_COPY[language][key];
}

export function playerPageLabel(language: PlayerLanguage, page: number, pageCount: number): string {
  return language === "en" ? `Page ${page} of ${pageCount}` : `Página ${page} de ${pageCount}`;
}

